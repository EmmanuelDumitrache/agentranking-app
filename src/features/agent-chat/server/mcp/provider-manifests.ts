function credentialFields(auth: McpProviderAuth): McpProviderManifest["credentialFields"] {
  if (auth.kind === "none") return [];
  if (auth.kind === "bearer") {
    return [{ key: "bearerToken", label: "API bearer token", secret: true, required: true }];
  }
  if (["api-key-header", "api-key-query", "api-key-tool-argument"].includes(auth.kind)) {
    return [{ key: "apiKey", label: "API key", secret: true, required: true }];
  }
  if (auth.kind === "oauth2") {
    return [{ key: "oauth", label: "Browser authorization", secret: true, required: true }];
  }
  return [
    { key: "clientId", label: "OAuth client ID", secret: false, required: true },
    { key: "clientSecret", label: "OAuth client secret", secret: true, required: true },
  ];
}

function reviewedProvider(seed: ProviderSeed): McpProviderManifest {
  const releaseStage = seed.releaseStage ?? "GA";
  const admission = seed.admission
    ?? (releaseStage === "BETA" || releaseStage === "EXPERIMENTAL"
      ? "REMOTE_BETA"
      : releaseStage === "EARLY_ACCESS"
        ? "REMOTE_SECURITY_REVIEW"
        : releaseStage === "WATCHLIST"
          ? "WATCHLIST"
          : "REMOTE_LAUNCH");
  const requiresUserConfirmation = seed.requiresUserConfirmation
    ?? seed.capabilityClasses.some((capability) =>
      ["SIMULATION", "TRANSACTION_PREP", "WALLET_APPROVAL", "TRADING", "PAID_CALLS", "ACCOUNT_ADMIN"]
        .includes(capability));
  return {
    key: seed.key,
    manifestVersion: 1,
    displayName: seed.displayName,
    publisherName: seed.publisherName ?? seed.displayName,
    publisherDomains: seed.publisherDomains,
    summary: seed.summary,
    categories: seed.categories,
    chainFamilies: seed.chainFamilies,
    capabilityClasses: seed.capabilityClasses,
    riskLevel: seed.riskLevel,
    billingModel: seed.billingModel,
    releaseStage,
    priority: seed.priority,
    credentialFields: seed.credentialFields ?? credentialFields(seed.auth),
    toolAllowlistSupport: seed.toolAllowlistSupport ?? false,
    toolAllowlistParameter: seed.toolAllowlistParameter,
    requiresUserConfirmation,
    reviewedAt: REVIEWED_AT,
    brand: {
      mark: seed.mark ?? seed.displayName.slice(0, 2).toUpperCase(),
      foreground: seed.foreground ?? "#ffffff",
      background: seed.background ?? "#334155",
      iconUrl: seed.iconUrl,
    },
    delivery: "remote",
    admission,
    endpoint: seed.endpoint,
    endpointVariants: seed.endpointVariants,
    transports: seed.transports ?? ["streamable-http"],
    auth: seed.auth,
    authOptions: seed.authOptions,
    baselineRisk: seed.baselineRisk ?? "READ_ONLY",
    curatedToolRules: seed.curatedToolRules ?? [],
    defaultBindingPolicy: {
      approvalMode: seed.approvalMode
        ?? (requiresUserConfirmation ? "CONFIRM_MUTATIONS" : "AUTO_READ_ONLY"),
      maxCallsPerRun: seed.maxCallsPerRun ?? 12,
      maxParallelCalls: seed.maxParallelCalls ?? 2,
    },
    evidence: [{
      url: seed.docsUrl,
      publisherControlled: true,
      checkedAt: REVIEWED_AT,
      supportsClaim: seed.evidenceClaims ?? ALL_CLAIMS,
    }],
    admissionReview: {
      capabilities: `${seed.summary} Tool-level policy remains authoritative for every discovered capability.`,
      dataAndCredentialHandling: seed.dataHandling
        ?? "Credentials are encrypted at rest and attached only at the reviewed provider request boundary; model-visible inputs never receive stored secrets.",
      rateLimitsAndCost: seed.cost
        ?? "Provider plans, quotas, credits, and rate limits remain authoritative; AgentRanking also applies bounded calls, concurrency, time, input, and output.",
      networkPolicy: "PINNED_HTTPS_RUNTIME_CHECKS",
      catalogPolicy: "BOUNDED_LIVE_DISCOVERY",
      failureAndRevocation: seed.revocation
        ?? "Users revoke or rotate credentials with the provider and can delete the encrypted local credential at any time.",
    },
    docsUrl: seed.docsUrl,
    termsUrl: seed.termsUrl,
    privacyUrl: seed.privacyUrl,
    notes: seed.notes,
  };
}

