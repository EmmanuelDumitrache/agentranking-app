import type { MiniAgent } from "@/components/home/home-types";
import type { DirectoryAgent } from "@/lib/agent-directory/types";
/** Map `/api/agents` list rows to the shared home scanner table shape. */
export function directoryAgentToMiniAgent(agent: DirectoryAgent): MiniAgent {
  return {
    id: agent.id,
    agentId: agent.agentId,
    chainId: agent.chainId,
    name: agent.name,
    score: agent.score,
    rank: agent.rank,
    organicRank: agent.organicRank,
    x402Support: agent.x402Support ?? undefined,
    description: agent.description,
    image: agent.image,
    isVerified: agent.isVerified ?? undefined,
    isPremiumVerified: agent.isPremiumVerified ?? undefined,
    sapVerified: agent.sapVerified ?? undefined,
    sapTwinMatch: agent.sapTwinMatch ?? undefined,
    hasDuplicateName: agent.hasDuplicateName ?? undefined,
    hotScore: agent.hotScore,
    powerScore: agent.powerScore,
    activeBoosts: agent.activeBoosts,
    adminPowerAdjust: agent.adminPowerAdjust,
    hasHolderPowerBoost: agent.hasHolderPowerBoost,
    createdAt: agent.createdAt,
    listedAt: agent.listedAt,
    lastActiveAt: agent.lastActiveAt,
    totalFeedback: agent.totalFeedback,
    chain: agent.chain,
    deploymentCount: agent.deploymentCount,
    chainLogoStack: agent.chainLogoStack,
    slug: agent.slug ?? undefined,
    profilePath: agent.profilePath,
    services: agent.services?.map((s) => ({ name: s.name })),
    agentRankScore: agent.agentRankScore,
    reputationScore: agent.reputationScore,
    protocolTrustScore: agent.protocolTrustScore,
    executionScore: agent.executionScore,
    archetype: agent.archetype,
    archetypeAuto: agent.archetypeAuto ? "true" : undefined,
    listingRegistrySource: agent.listingRegistrySource,
    metaplexVerified: agent.metaplexVerified ?? undefined,
    metaplexAssetAddress: agent.metaplexAssetAddress,
    metaplexAgentTokenMint: agent.metaplexAgentTokenMint,
    isClaimed: agent.isClaimed ?? undefined,
    clusterChainVerified: agent.clusterChainVerified ?? undefined,
    clusterIdentityRegistered: agent.clusterIdentityRegistered ?? undefined,
  };
}
