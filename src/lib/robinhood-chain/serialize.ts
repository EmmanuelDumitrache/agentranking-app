import type { RobinhoodChainLaunch } from "@/generated/prisma/client";
import type { RobinhoodLaunchRecord } from "@/lib/robinhood-chain/types";
export function serializeRobinhoodLaunch(row: RobinhoodChainLaunch): RobinhoodLaunchRecord {
  return {
    id: row.id,
    tokenAddress: row.tokenAddress,
    creatorWallet: row.creatorWallet,
    poolAddress: row.poolAddress,
    pairToken: row.pairToken,
    dexFactory: row.dexFactory,
    dexId: row.dexId,
    launchConfigId: row.launchConfigId,
    positionId: row.positionId,
    restrictionsEndBlock: row.restrictionsEndBlock,
    initialBuyAmount: row.initialBuyAmount,
    txHash: row.txHash,
    blockNumber: row.blockNumber,
    blockTimestamp: row.blockTimestamp.toISOString(),
    chainId: row.chainId,
    source: row.source,
    frontendSourceLabel: row.frontendSourceLabel,
    launchedViaAgentRanking: row.launchedViaAgentRanking,
    sourceVerified: row.sourceVerified,
    feeSplitterAddress: row.feeSplitterAddress,
    creatorFeeBps: row.creatorFeeBps,
    arFeeBps: row.protocolFeeBps,
    tokenName: row.tokenName,
    tokenSymbol: row.tokenSymbol,
    tokenDescription: row.tokenDescription,
    tokenImageUrl: row.tokenImageUrl,
    tokenImageOriginalUrl: row.tokenImageOriginalUrl,
    tokenLogoIpfsCid: row.tokenLogoIpfsCid,
    tokenLogoIpfsUri: row.tokenLogoIpfsUri,
    tokenLogoGatewayUrl: row.tokenLogoGatewayUrl,
    onChainLogoUrl: row.onChainLogoUrl,
    website: row.website,
    twitter: row.twitter,
    telegram: row.telegram,
    discord: row.discord,
    farcaster: row.farcaster,
    agentDbId: row.agentDbId,
    decimals: row.decimals,
    totalSupply: row.totalSupply,
    onChainPoolFee: row.onChainPoolFee,
    maxWalletLimit: row.maxWalletLimit,
    maxTxLimit: row.maxTxLimit,
    onChainRestrictionEndBlock: row.onChainRestrictionEndBlock,
    createdAt: row.createdAt.toISOString(),
    updatedAt: row.updatedAt.toISOString(),
  };
}